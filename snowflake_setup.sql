CREATE WAREHOUSE IF NOT EXISTS GEOPULSE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS GEOPULSE_DB;
CREATE SCHEMA IF NOT EXISTS GEOPULSE_DB.RAW;

CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.DEVICE_PINGS (
  DEVICE_ID VARCHAR NOT NULL,
  LOCATION GEOGRAPHY,
  PING_TIMESTAMP TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.STORES (
  STORE_ID VARCHAR NOT NULL,
  NAME VARCHAR,
  LOCATION GEOGRAPHY
);

USE WAREHOUSE GEOPULSE_WH;
USE DATABASE GEOPULSE_DB;
USE SCHEMA RAW;

-- Quick checks
SELECT COUNT(*) AS PING_ROWS FROM DEVICE_PINGS;

SELECT DATE_TRUNC('HOUR', PING_TIMESTAMP) AS PING_HOUR, COUNT(*) AS PING_COUNT
FROM DEVICE_PINGS
GROUP BY PING_HOUR
ORDER BY PING_HOUR;

SELECT
  (SELECT COUNT_IF(LOCATION IS NULL) FROM DEVICE_PINGS) AS PINGS_WITH_NULL_LOCATION,
  (SELECT COUNT_IF(LOCATION IS NULL) FROM STORES) AS STORES_WITH_NULL_LOCATION;
